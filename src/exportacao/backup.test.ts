import { afterEach, describe, expect, it, vi } from 'vitest'
import { criarBancoTeste, type BancoTeste } from '../testes/dbTeste'
import { exportarDadosJson, gerarBackup, LIMITE_BACKUP_BYTES, montarDadosBackup } from './backup'
import { continuarRestauracao, lerBackup, restauracaoPendente, restaurarBackup } from './restaurar'
import { validarBackup } from './schemaBackup'

describe('backup e restauração', () => {
  const abertos: BancoTeste[] = []
  afterEach(async () => {
    vi.restoreAllMocks()
    for (const t of abertos.splice(0)) await t.fechar()
  })

  async function popular(t: BancoTeste) {
    await t.servicos.estrutura.definirTaxa({ quartos: 3, valorCentavos: 45000, vigenteDesde: '2026-09' })
    await t.servicos.estrutura.definirTaxa({ quartos: 2, valorCentavos: 35000, vigenteDesde: '2026-09' })
    await t.servicos.cobrancas.gerar('2026-09')
    const cat = await t.categoriaId('Água e esgoto')
    await t.servicos.lancamentos.registrar({ natureza: 'DESPESA', data: '2026-09-10', valorCentavos: 100000, descricao: 'Água', categoriaId: cat, escopoTipo: 'GERAL' }, [
      { nome: 'conta.pdf', mime: 'application/pdf', blob: new Blob(['%PDF-conta']) },
    ])
    await t.servicos.documentos.criar({ titulo: 'Ata', categoria: 'ATA', data: '2026-09-01' }, [{ nome: 'ata', mime: 'image/png', blob: new Blob(['png-bytes']) }])
    await t.servicos.sistema.concluirOnboarding()
  }

  it('round-trip completo: tabelas iguais, anexos com extensão e binários preservados', async () => {
    const origem = criarBancoTeste()
    abertos.push(origem)
    await popular(origem)
    const { blob, nome, dados } = await gerarBackup(origem.db, { agora: '2026-09-04T10:00:00', navegador: 'teste' })
    expect(nome).toBe('backup-Meu Condomínio-2026-09-04.zip')
    expect(dados.contagens).toMatchObject({ blocos: 14, unidades: 320, cobrancas: 320, lancamentos: 1, anexos: 2, documentos: 1 })
    expect(dados.tabelas.anexos.map((a) => a.arquivo.split('.').pop()).sort()).toEqual(['pdf', 'png'])

    const destino = criarBancoTeste('2026-09-05T08:00:00')
    abertos.push(destino)
    const { zip, previa } = await lerBackup(blob)
    expect(previa.anexosNoZip).toBe(2)
    expect(previa.faltantes).toEqual([])
    await restaurarBackup(destino.db, zip, previa.dados, '2026-09-05T08:00:00')

    expect(await destino.db.lancamentos.toArray()).toEqual(await origem.db.lancamentos.toArray())
    expect(await destino.db.cobrancas.count()).toBe(320)
    expect(await destino.db.blocos.toArray()).toEqual(await origem.db.blocos.toArray())
    expect((await destino.db.anexos.toArray()).map((a) => a.nome).sort()).toEqual(['ata', 'conta.pdf'])
    const anexoPdf = (await destino.db.anexos.toArray()).find((a) => a.nome === 'conta.pdf')!
    const b = await destino.db.anexosBlob.get(anexoPdf.id)
    expect(await b?.blob.text()).toBe('%PDF-conta')
    expect(b?.blob.type).toBe('application/pdf')
    expect(await restauracaoPendente(destino.db)).toBeNull()
    expect(await destino.servicos.sistema.onboardingConcluido()).toBe(true)
    expect((await destino.servicos.sistema.estadoBackup()).ultimoBackupEm).toBe('2026-09-04T10:00:00')
    expect((await destino.consultas.auditoria.ultimas(1))[0]?.acao).toBe('restaurado')
  })

  it('backup só de um ano leva os dados completos e apenas os anexos daquele ano; faltantes são apontados', async () => {
    const t = criarBancoTeste()
    abertos.push(t)
    await popular(t)
    const dados2025 = await montarDadosBackup(t.db, { agora: '2026-09-04T10:00:00', anoDosAnexos: 2025 })
    expect(dados2025.tabelas.anexos).toHaveLength(2)
    expect(dados2025.tabelas.anexos.every(a => a.incluido === false)).toBe(true)
    expect(dados2025.tabelas.lancamentos).toHaveLength(1)
    const { blob } = await gerarBackup(t.db, { agora: '2026-09-04T10:00:00', anoDosAnexos: 2026 })
    const { previa } = await lerBackup(blob)
    expect(previa.anexosNoZip).toBe(2)
    const json = await exportarDadosJson(t.db, '2026-09-04T10:00:00')
    expect(json.nome).toBe('dados-Meu Condomínio-2026-09-04.json')
  })

  it('restaura anexos de anos diferentes sem perder metadados nem aceitar outra instalação', async () => {
    const origem = criarBancoTeste()
    const destino = criarBancoTeste()
    const outro = criarBancoTeste()
    abertos.push(origem, destino, outro)
    await popular(origem)
    const [anexo] = await origem.db.anexos.toArray()
    await origem.db.anexos.update(anexo!.id, { criadoEm: '2025-12-20T10:00:00' })
    const a = await gerarBackup(origem.db, { agora: '2026-09-04T10:00:00', anoDosAnexos: 2026 })
    const b = await gerarBackup(origem.db, { agora: '2026-09-04T11:00:00', anoDosAnexos: 2025 })
    const primeiro = await lerBackup(a.blob)
    expect(primeiro.previa.omitidosPorAno).toBe(1)
    expect(primeiro.previa.faltantes).toEqual([])
    await restaurarBackup(destino.db, primeiro.zip, primeiro.previa.dados, '2026-09-05T10:00:00')
    expect(await destino.db.anexos.count()).toBe(2)
    expect(await destino.db.anexosBlob.count()).toBe(1)
    expect(await restauracaoPendente(destino.db)).toMatchObject({ esperados: 2, gravados: 1, anoDosAnexos: 2026 })
    await destino.servicos.estrutura.atualizarCondominio({ nome: 'Nome atualizado após restaurar', diaVencimento: 10 })
    expect((await destino.servicos.sistema.estadoBackup()).alteracoesDesdeBackup).toBe(1)
    const errado = await gerarBackup(outro.db, { agora: '2026-09-04T10:00:00' })
    const zipErrado = await lerBackup(errado.blob)
    await expect(continuarRestauracao(destino.db, zipErrado.zip, zipErrado.previa.dados, '2026-09-05T10:00:00')).rejects.toMatchObject({ codigo: 'BACKUP' })
    expect(await restauracaoPendente(destino.db)).not.toBeNull()
    const segundo = await lerBackup(b.blob)
    await continuarRestauracao(destino.db, segundo.zip, segundo.previa.dados, '2026-09-05T10:00:00')
    expect(await destino.db.anexos.count()).toBe(2)
    expect(await destino.db.anexosBlob.count()).toBe(2)
    expect(await restauracaoPendente(destino.db)).toBeNull()
    expect((await destino.consultas.condominio())?.nome).toBe('Nome atualizado após restaurar')
    expect(await destino.servicos.sistema.estadoBackup()).toEqual({ ultimoBackupEm: '2026-09-04T10:00:00', alteracoesDesdeBackup: 1 })
  })

  it('retoma só o lote que faltou após falha de gravação sem duplicar anexos', async () => {
    const origem = criarBancoTeste()
    const destino = criarBancoTeste()
    abertos.push(origem, destino)
    await origem.servicos.documentos.criar({ titulo: 'Arquivo de atas', categoria: 'ATA', data: '2026-09-01' },
      Array.from({ length: 201 }, (_, i) => ({ nome: `${i}.txt`, mime: 'text/plain', blob: new Blob([`ata-${i}`]) })))
    const { blob } = await gerarBackup(origem.db, { agora: '2026-09-04T10:00:00' })
    const { zip, previa } = await lerBackup(blob)
    const gravar = destino.db.anexosBlob.bulkPut.bind(destino.db.anexosBlob)
    const falha = vi.spyOn(destino.db.anexosBlob, 'bulkPut').mockImplementationOnce(gravar).mockRejectedValueOnce(new Error('Sem espaço'))
    await expect(restaurarBackup(destino.db, zip, previa.dados, '2026-09-05T10:00:00')).rejects.toThrow('Sem espaço')
    expect(await destino.db.anexosBlob.count()).toBe(200)
    expect(await restauracaoPendente(destino.db)).toMatchObject({ esperados: 201, gravados: 200 })
    falha.mockRestore()
    const retomada = vi.spyOn(destino.db.anexosBlob, 'bulkPut')
    await continuarRestauracao(destino.db, zip, previa.dados, '2026-09-05T11:00:00')
    expect(retomada).toHaveBeenCalledTimes(1)
    expect(retomada.mock.calls[0]?.[0]).toHaveLength(1)
    expect(await destino.db.anexosBlob.count()).toBe(201)
    expect(await restauracaoPendente(destino.db)).toBeNull()
    const ultimo = previa.dados.tabelas.anexos.at(-1)!
    expect(await (await destino.db.anexosBlob.get(ultimo.id))?.blob.text()).toBe(`ata-${ultimo.nome.split('.')[0]}`)
  })

  it('recusa metadados e binário incompatíveis e mantém a restauração recuperável', async () => {
    const origem = criarBancoTeste()
    const destino = criarBancoTeste()
    abertos.push(origem, destino)
    await popular(origem)
    const parcial = await lerBackup((await gerarBackup(origem.db, { agora: '2026-09-04T10:00:00', anoDosAnexos: 2025 })).blob)
    await restaurarBackup(destino.db, parcial.zip, parcial.previa.dados, '2026-09-05T10:00:00')
    const completo = await lerBackup((await gerarBackup(origem.db, { agora: '2026-09-04T11:00:00' })).blob)
    const divergente = structuredClone(completo.previa.dados)
    divergente.tabelas.anexos[0]!.nome = 'Outro arquivo.pdf'
    await expect(continuarRestauracao(destino.db, completo.zip, divergente, '2026-09-05T10:00:00')).rejects.toMatchObject({ codigo: 'BACKUP' })
    expect(await destino.db.anexosBlob.count()).toBe(0)
    const anexo = completo.previa.dados.tabelas.anexos[0]!
    const binario = await completo.zip.file(anexo.arquivo)!.async('uint8array')
    completo.zip.file(anexo.arquivo, 'truncado')
    await expect(continuarRestauracao(destino.db, completo.zip, completo.previa.dados, '2026-09-05T10:00:00')).rejects.toMatchObject({ codigo: 'BACKUP' })
    expect(await restauracaoPendente(destino.db)).toMatchObject({ esperados: 2, gravados: 0 })
    completo.zip.file(anexo.arquivo, binario)
    await continuarRestauracao(destino.db, completo.zip, completo.previa.dados, '2026-09-05T10:00:00')
    expect(await restauracaoPendente(destino.db)).toBeNull()
  })

  it('ignora anexos de um arquivo anual antigo que foram removidos do snapshot restaurado', async () => {
    const origem = criarBancoTeste()
    const destino = criarBancoTeste()
    abertos.push(origem, destino)
    await popular(origem)
    const removido = await origem.servicos.documentos.criar({ titulo: 'Rascunho', categoria: 'OUTRO', data: '2026-09-01' }, [{ nome: 'rascunho.txt', mime: 'text/plain', blob: new Blob(['rascunho']) }])
    const anexoRemovido = (await origem.servicos.anexos.listar('DOCUMENTO', removido.id))[0]!
    const antigo = await lerBackup((await gerarBackup(origem.db, { agora: '2026-09-04T10:00:00', anoDosAnexos: 2026 })).blob)
    await origem.servicos.documentos.excluir(removido.id)
    const parcial = await lerBackup((await gerarBackup(origem.db, { agora: '2026-09-04T11:00:00', anoDosAnexos: 2025 })).blob)
    await restaurarBackup(destino.db, parcial.zip, parcial.previa.dados, '2026-09-05T10:00:00')
    await continuarRestauracao(destino.db, antigo.zip, antigo.previa.dados, '2026-09-05T10:00:00')
    expect(await destino.db.anexosBlob.count()).toBe(2)
    expect(await destino.db.anexosBlob.get(anexoRemovido.id)).toBeUndefined()
    expect(await destino.db.documentos.get(removido.id)).toBeUndefined()
    expect(await restauracaoPendente(destino.db)).toBeNull()
  })

  it('desfaz a troca dos registros se uma chave única estiver duplicada no backup', async () => {
    const origem = criarBancoTeste()
    const destino = criarBancoTeste()
    abertos.push(origem, destino)
    await destino.servicos.estrutura.atualizarCondominio({ nome: 'Dados atuais preservados', diaVencimento: 10 })
    const antes = await montarDadosBackup(destino.db, { agora: '2026-09-04T10:00:00' })
    const { blob } = await gerarBackup(origem.db, { agora: '2026-09-04T10:00:00' })
    const { zip, previa } = await lerBackup(blob)
    previa.dados.tabelas.unidades.push({ ...previa.dados.tabelas.unidades[0]!, id: 'unidade-duplicada' })
    previa.dados.contagens.unidades = previa.dados.tabelas.unidades.length
    await expect(restaurarBackup(destino.db, zip, previa.dados, '2026-09-05T10:00:00')).rejects.toThrow()
    expect((await montarDadosBackup(destino.db, { agora: '2026-09-04T10:00:00' })).tabelas).toEqual(antes.tabelas)
    expect(await restauracaoPendente(destino.db)).toBeNull()
  })

  it('recusa gerar backup com anexo ausente ou de tamanho divergente', async () => {
    const origem = criarBancoTeste()
    abertos.push(origem)
    await popular(origem)
    const anexo = (await origem.db.anexos.toArray())[0]!
    await origem.db.anexosBlob.put({ id: anexo.id, blob: new Blob(['truncado']) })
    await expect(gerarBackup(origem.db, { agora: '2026-09-04T10:00:00' })).rejects.toMatchObject({ codigo: 'BACKUP' })
    await origem.db.anexosBlob.delete(anexo.id)
    await expect(gerarBackup(origem.db, { agora: '2026-09-04T10:00:00' })).rejects.toMatchObject({ codigo: 'BACKUP' })
    await expect(gerarBackup(origem.db, { agora: '2026-09-04T10:00:00', anoDosAnexos: 2025 })).resolves.toHaveProperty('blob')
  })

  it('recusa anexos declarados acima do limite antes de substituir os registros', async () => {
    const origem = criarBancoTeste()
    const destino = criarBancoTeste()
    abertos.push(origem, destino)
    await popular(origem)
    const { zip, previa } = await lerBackup((await gerarBackup(origem.db, { agora: '2026-09-04T10:00:00' })).blob)
    previa.dados.tabelas.anexos[0]!.tamanho = LIMITE_BACKUP_BYTES + 1
    const antes = await destino.db.condominio.get('unico')
    await expect(restaurarBackup(destino.db, zip, previa.dados, '2026-09-05T10:00:00')).rejects.toMatchObject({ codigo: 'BACKUP' })
    expect(await destino.db.condominio.get('unico')).toEqual(antes)
    expect(await restauracaoPendente(destino.db)).toBeNull()
    zip.file('dados.json', JSON.stringify(previa.dados))
    await expect(lerBackup(await zip.generateAsync({ type: 'blob' }))).rejects.toMatchObject({ codigo: 'BACKUP' })
  })

  it('mantém pendência com arquivo ausente; recusa backup errado e retoma com o mesmo ZIP', async () => {
    const origem = criarBancoTeste()
    const destino = criarBancoTeste()
    abertos.push(origem, destino)
    await popular(origem)
    const { blob } = await gerarBackup(origem.db, { agora: '2026-09-04T10:00:00' })
    const completo = await lerBackup(blob)
    const incompleto = await lerBackup(blob)
    incompleto.zip.remove(incompleto.previa.dados.tabelas.anexos[0]!.arquivo)
    await restaurarBackup(destino.db, incompleto.zip, incompleto.previa.dados, '2026-09-05T10:00:00')
    expect(await restauracaoPendente(destino.db)).toMatchObject({ gravados: 1, esperados: 2 })
    await expect(continuarRestauracao(destino.db, completo.zip, { ...completo.previa.dados, geradoEm: '2026-08-01T00:00:00' }, '2026-09-05T10:00:00')).rejects.toMatchObject({ codigo: 'BACKUP' })
    await continuarRestauracao(destino.db, completo.zip, completo.previa.dados, '2026-09-05T10:00:00')
    expect(await restauracaoPendente(destino.db)).toBeNull()
    expect(await destino.db.anexosBlob.count()).toBe(2)
  })

  it('valida campos essenciais antes de tocar nos dados e migra backup schema 1', async () => {
    const origem = criarBancoTeste()
    const destino = criarBancoTeste()
    abertos.push(origem, destino)
    await popular(origem)
    const { blob, dados } = await gerarBackup(origem.db, { agora: '2026-09-04T10:00:00' })
    const { zip } = await lerBackup(blob)
    const invalido = { ...dados, tabelas: { ...dados.tabelas, lancamentos: [{ id: 'x', status: 'ATIVO' }] } }
    expect(() => validarBackup(invalido)).toThrow()
    await destino.servicos.estrutura.atualizarCondominio({ nome: 'Preservado', diaVencimento: 10 })
    await expect(restaurarBackup(destino.db, zip, invalido as typeof dados, '2026-09-05T10:00:00')).rejects.toMatchObject({ codigo: 'BACKUP' })
    expect((await destino.consultas.condominio())?.nome).toBe('Preservado')
    const legado = { ...dados, schemaVersion: 1, tabelas: { ...dados.tabelas, fechamentos: undefined, lancamentos: dados.tabelas.lancamentos.map(({ tipo: _t, estornaLancamentoId: _e, estornadoPorId: _p, ...l }) => l) } }
    zip.file('dados.json', JSON.stringify(legado))
    const lido = await lerBackup(await zip.generateAsync({ type: 'blob' }))
    await restaurarBackup(destino.db, lido.zip, lido.previa.dados, '2026-09-05T10:00:00')
    expect((await destino.db.lancamentos.toArray())[0]).toMatchObject({ tipo: 'NORMAL', estornaLancamentoId: null, estornadoPorId: null })
    expect(await destino.consultas.meta('schemaVersion')).toBe(2)
  })

  it('rejeita arquivos inválidos, JSON corrompido e versão de schema mais nova', async () => {
    await expect(lerBackup(new Blob(['nao e zip']))).rejects.toMatchObject({ codigo: 'BACKUP' })
    expect(() => validarBackup({ formato: 'outro' })).toThrow()
    const t = criarBancoTeste()
    abertos.push(t)
    const dados = await montarDadosBackup(t.db, { agora: '2026-09-04T10:00:00' })
    const { default: JSZip } = await import('jszip')
    const semDados = new JSZip()
    semDados.file('LEIA-ME.txt', 'Arquivo incompleto')
    await expect(lerBackup(await semDados.generateAsync({ type: 'blob' }))).rejects.toMatchObject({ codigo: 'BACKUP' })
    expect(() => validarBackup({ ...dados, tabelas: { ...dados.tabelas, condominio: [] } })).toThrow()
    expect(() => validarBackup({ ...dados, contagens: { ...dados.contagens, blocos: 0 } })).toThrow()
    const zip = new JSZip()
    zip.file('dados.json', JSON.stringify({ ...dados, schemaVersion: 99 }))
    await expect(lerBackup(await zip.generateAsync({ type: 'blob' }))).rejects.toMatchObject({ codigo: 'BACKUP' })
    const zip2 = new JSZip()
    zip2.file('dados.json', '{corrompido')
    await expect(lerBackup(await zip2.generateAsync({ type: 'blob' }))).rejects.toMatchObject({ codigo: 'BACKUP' })
  })
})
